/*
 * A resource's page badges a field Read only when only OneUptime writes it
 * - the id and the dates, who created the record and who last modified it
 * (#10527) - as the spec marks it readOnly (ModelSchema
 * .isWrittenOnlyByOneUptime). It said so only inside the field's folded
 * permissions before ("Create: Autogenerated", "Update: Cannot update").
 */

jest.mock("../../../FeatureSet/APIReference/Utils/Config", () => {
  const path: typeof Path = jest.requireActual("path") as typeof Path;
  const root: string = path.resolve(
    __dirname,
    "../../../FeatureSet/APIReference",
  );
  return {
    ViewsPath: path.join(root, "views"),
    StaticPath: path.join(root, "Static"),
    CodeExamplesPath: path.join(root, "CodeExamples"),
  };
});

interface PageColumn extends TableColumnMetadata {
  readOnly: boolean;
}

async function pageColumns(
  resource: ModelDocumentation,
): Promise<Dictionary<PageColumn>> {
  let locals: Record<string, unknown> = {};

  const req: ExpressRequest = {
    params: { lang: "en", page: resource.path },
    originalUrl: `/reference/en/${resource.path}`,
    headers: {},
  } as unknown as ExpressRequest;

  const res: unknown = {
    status: (): unknown => {
      return res;
    },
    render: (_view: string, renderLocals: Record<string, unknown>): void => {
      locals = renderLocals;
    },
  };

  await ModelServiceHandler.executeResponse(req, res as ExpressResponse);

  return ((locals["pageData"] as Record<string, unknown>)?.["columns"] ||
    {}) as Dictionary<PageColumn>;
}

function resourceOf(modelType: DatabaseBaseModelType): ModelDocumentation {
  const resource: ModelDocumentation | undefined =
    ResourceUtil.getResources().find((candidate: ModelDocumentation) => {
      return candidate.model.constructor === modelType;
    });

  if (!resource) {
    throw new Error(`${modelType.name} has no page`);
  }

  return resource;
}

describe("the Read only badge on a resource's page", () => {
  let monitor: Dictionary<PageColumn>;

  beforeAll(async () => {
    monitor = await pageColumns(resourceOf(Monitor));
  }, 120000);

  it("is on what created a monitor and who last modified it, which the page now lists", () => {
    for (const column of RECORD_ACTOR_COLUMNS) {
      expect([column, monitor[column]?.readOnly]).toEqual([column, true]);
    }
  });

  it("is on the id and the dates, and on who created it", () => {
    for (const column of ["_id", "createdAt", "updatedAt", "createdByUserId"]) {
      expect([column, monitor[column]?.readOnly]).toEqual([column, true]);
    }
  });

  it("is not on what a create or an update sends", () => {
    for (const column of ["name", "description", "monitorType"]) {
      expect([column, monitor[column]?.readOnly]).toEqual([column, false]);
    }
  });

  it("is not about who deleted a monitor, which is no field", () => {
    expect(monitor["deletedByUserId"]).toBeUndefined();
    expect(monitor["deletedByUser"]).toBeUndefined();
  });

  it("on every resource, is on exactly the fields the spec marks read only", async () => {
    const wrong: Array<string> = [];

    for (const resource of ResourceUtil.getResources()) {
      if (resource.isAnalytics) {
        continue;
      }

      const columns: Dictionary<PageColumn> = await pageColumns(resource);

      for (const key of Object.keys(columns)) {
        const column: PageColumn = columns[key]!;

        if (column.readOnly !== ModelSchema.isWrittenOnlyByOneUptime(column)) {
          wrong.push(`${resource.path}.${key}`);
        }
      }
    }

    expect(wrong).toEqual([]);
  }, 600000);

  it("lists who last modified a record on every resource whose readers may read who created it", async () => {
    const missing: Array<string> = [];

    for (const resource of ResourceUtil.getResources()) {
      if (resource.isAnalytics) {
        continue;
      }

      const model: BaseModel = resource.model as BaseModel;
      const readers: number =
        model.getColumnAccessControlForAllColumns()["lastModifiedAt"]?.read
          ?.length || 0;

      if (readers === 0) {
        continue;
      }

      const columns: Dictionary<PageColumn> = await pageColumns(resource);

      if (!columns["lastModifiedAt"]?.readOnly) {
        missing.push(resource.path);
      }
    }

    expect(missing).toEqual([]);
  }, 600000);
});

describe("the badge as it is drawn", () => {
  // The fixture's monitor page, with its id and creation date read only.
  function fixtureWithReadOnlyColumns(): PageFixture {
    const fixture: PageFixture = JSON.parse(
      JSON.stringify(PAGE_FIXTURES["model"]!),
    ) as PageFixture;
    const columns: Record<string, Record<string, unknown>> = (
      fixture.pageData as { columns: Record<string, Record<string, unknown>> }
    ).columns;

    columns["_id"]!["readOnly"] = true;
    columns["createdAt"]!["readOnly"] = true;

    return fixture;
  }

  // The list item of one column on the page.
  function item(html: string, key: string): string {
    const start: number = html.indexOf(
      `<code class="model-inline-code">${key}</code>`,
    );

    expect(start).toBeGreaterThan(-1);

    return html.slice(start, html.indexOf("</li>", start));
  }

  it("badges the read-only columns, in the page's own font, and no other", async () => {
    const html: string = await renderPage(fixtureWithReadOnlyColumns());

    expect(item(html, "_id")).toContain(">Read only<");
    expect(item(html, "createdAt")).toContain(">Read only<");
    expect(item(html, "name")).not.toContain(">Read only<");

    const createdAt: string = item(html, "createdAt");
    const badge: string = createdAt.slice(
      createdAt.lastIndexOf("<span", createdAt.indexOf(">Read only<")),
      createdAt.indexOf(">Read only<"),
    );

    expect(badge).toContain("font-sans");
  });

  it("says it in the reader's language", async () => {
    const html: string = await renderPage(fixtureWithReadOnlyColumns(), {
      lang: "de",
    });

    expect(item(html, "createdAt")).toContain(">Schreibgeschützt<");
    expect(item(html, "createdAt")).not.toContain(">Read only<");
  });
});
