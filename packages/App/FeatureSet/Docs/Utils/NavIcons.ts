/*
 * The icon for a category key, or the default document icon. Only the map's
 * own keys count: "constructor" or "__proto__" must not find Object's.
 */
export const getDocsNavIcon: (key: string) => string = (
  key: string,
): string => {
  return Object.prototype.hasOwnProperty.call(DocsNavIcons, key)
    ? DocsNavIcons[key]!
    : DOCS_DEFAULT_ICON;
};

export const hasDocsNavIcon: (key: string) => boolean = (
  key: string,
): boolean => {
  return Object.prototype.hasOwnProperty.call(DocsNavIcons, key);
};

