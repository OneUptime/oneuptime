const markOf: (
  path: string,
  displayName: string,
) => FunctionComponent<MarkProps> = (
  path: string,
  displayName: string,
): FunctionComponent<MarkProps> => {
  const Mark: FunctionComponent<MarkProps> = (
    props: MarkProps,
  ): ReactElement => {
    return (
      <svg
        className={props.className || "h-5 w-5"}
        fill="currentColor"
        viewBox="0 0 24 24"
        aria-hidden="true"
      >
        <path d={path} />
      </svg>
    );
  };

  Mark.displayName = displayName;

  return Mark;
};

