import OnlineDdl from "../../../../Server/Infrastructure/Postgres/OnlineDdl";
import { AddGlobalRunners1803950000000 } from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/1803950000000-AddGlobalRunners";
import { AddGlobalRunnerJobIndex1804000000000 } from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/1804000000000-AddGlobalRunnerJobIndex";
import SchemaMigrations from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/Index";
import { MigrationInterface, QueryRunner } from "typeorm";
import fs from "fs";
import path from "path";
import { afterEach, describe, expect, test } from "@jest/globals";

/*
 * The global Runners' migrations, generated by TypeORM against a fully
 * migrated throwaway database (and checked for drift against it):
 *
 *   - AddGlobalRunners adds the four columns with the defaults the product
 *     relies on - a project uses global Runners (true), a Runner and a job
 *     are not global and a secret is not for global Runners until someone
 *     says so (false) - and lets a Runner have no project. Nothing else: the
 *     generator's drop and re-add of the Runner's project key (only because
 *     the column's nullability changed) is left out, as it would check every
 *     Runner row while blocking writers;
 *   - AddGlobalRunnerJobIndex builds the index the global claim reads by,
 *     online, outside a transaction.
 */

const TRAILING_TIMESTAMP_PATTERN: RegExp = /(\d+)$/;

type MigrationClass = new () => MigrationInterface;

async function record(
  migration: MigrationInterface,
  direction: "up" | "down",
): Promise<Array<string>> {
  const steps: Array<string> = [];

  const runner: QueryRunner = {
    isTransactionActive: false,
    query: async (sql: string): Promise<void> => {
      steps.push(sql);
    },
  } as unknown as QueryRunner;

  jest.spyOn(OnlineDdl, "createIndex").mockImplementation((async (
    _runner: QueryRunner,
    statement: string,
  ) => {
    steps.push(`online: ${statement}`);
  }) as never);
  jest.spyOn(OnlineDdl, "dropIndex").mockImplementation((async (
    _runner: QueryRunner,
    statement: string,
  ) => {
    steps.push(`online: ${statement}`);
  }) as never);

  if (direction === "up") {
    await migration.up(runner);
  } else {
    await migration.down(runner);
  }

  return steps;
}

function timestampOf(migration: MigrationClass): number {
  const match: RegExpMatchArray | null = migration.name.match(
    TRAILING_TIMESTAMP_PATTERN,
  );

  return match ? parseInt(match[1]!, 10) : 0;
}

afterEach(() => {
  jest.restoreAllMocks();
});

describe("the global Runners' migrations", () => {
  test("name themselves after their timestamps", () => {
    expect(new AddGlobalRunners1803950000000().name).toBe(
      "AddGlobalRunners1803950000000",
    );
    expect(new AddGlobalRunnerJobIndex1804000000000().name).toBe(
      "AddGlobalRunnerJobIndex1804000000000",
    );
  });

  test("are registered once each, the columns before the index, after every older migration", () => {
    const registered: Array<MigrationClass> =
      SchemaMigrations as Array<MigrationClass>;

    for (const migration of [
      AddGlobalRunners1803950000000,
      AddGlobalRunnerJobIndex1804000000000,
    ] as Array<MigrationClass>) {
      expect(
        registered.filter((candidate: MigrationClass) => {
          return candidate === migration;
        }),
      ).toHaveLength(1);

      const index: number = registered.indexOf(migration);

      for (let before: number = 0; before < index; before++) {
        expect(timestampOf(registered[before]!)).toBeLessThan(
          timestampOf(migration),
        );
      }
    }

    expect(registered.indexOf(AddGlobalRunners1803950000000)).toBeLessThan(
      registered.indexOf(AddGlobalRunnerJobIndex1804000000000),
    );
  });

  test("each is backed by exactly one file carrying its timestamp", () => {
    const directory: string = path.join(
      __dirname,
      "../../../../Server/Infrastructure/Postgres/SchemaMigrations",
    );
    const files: Array<string> = fs.readdirSync(directory);

    expect(
      files.filter((file: string) => {
        return file.startsWith("1803950000000-");
      }),
    ).toEqual(["1803950000000-AddGlobalRunners.ts"]);
    expect(
      files.filter((file: string) => {
        return file.startsWith("1804000000000-");
      }),
    ).toEqual(["1804000000000-AddGlobalRunnerJobIndex.ts"]);
  });

  test("adds the four columns with their defaults, lets a Runner have no project, and touches nothing else", async () => {
    expect(await record(new AddGlobalRunners1803950000000(), "up")).toEqual([
      `ALTER TABLE "Project" ADD "useGlobalRunners" boolean NOT NULL DEFAULT true`,
      `ALTER TABLE "Runner" ADD "isGlobalRunner" boolean NOT NULL DEFAULT false`,
      `ALTER TABLE "RunnerJob" ADD "runsOnGlobalRunner" boolean NOT NULL DEFAULT false`,
      `ALTER TABLE "RunbookSecret" ADD "isAvailableToGlobalRunners" boolean NOT NULL DEFAULT false`,
      `ALTER TABLE "Runner" ALTER COLUMN "projectId" DROP NOT NULL`,
    ]);
  });

  test("leaves the Runner's project key as it was: no key is dropped or checked again", async () => {
    const up: Array<string> = await record(
      new AddGlobalRunners1803950000000(),
      "up",
    );

    for (const statement of up) {
      expect(statement).not.toContain("CONSTRAINT");
      expect(statement).not.toContain("FOREIGN KEY");
    }
  });

  test("an existing project uses global Runners; an existing secret reaches only the Runners it was assigned", async () => {
    const up: Array<string> = await record(
      new AddGlobalRunners1803950000000(),
      "up",
    );

    expect(up).toContain(
      `ALTER TABLE "Project" ADD "useGlobalRunners" boolean NOT NULL DEFAULT true`,
    );
    expect(up).toContain(
      `ALTER TABLE "RunbookSecret" ADD "isAvailableToGlobalRunners" boolean NOT NULL DEFAULT false`,
    );
  });

  test("the column migration runs in a transaction", () => {
    expect(
      (
        new AddGlobalRunners1803950000000() as unknown as {
          transaction?: boolean;
        }
      ).transaction,
    ).toBeUndefined();
  });

  test("the claim's index is built online, outside a transaction, exactly as generated", async () => {
    const migration: AddGlobalRunnerJobIndex1804000000000 =
      new AddGlobalRunnerJobIndex1804000000000();

    expect(migration.transaction).toBe(false);
    expect(await record(migration, "up")).toEqual([
      `online: CREATE INDEX "IDX_f1fb288722f84d308332c8109b" ON "RunnerJob" ("runsOnGlobalRunner") `,
    ]);
  });

  test("down() undoes each, removing the global Runners before the project becomes required again", async () => {
    expect(
      await record(new AddGlobalRunnerJobIndex1804000000000(), "down"),
    ).toEqual([`online: DROP INDEX "public"."IDX_f1fb288722f84d308332c8109b"`]);

    expect(await record(new AddGlobalRunners1803950000000(), "down")).toEqual([
      `DELETE FROM "Runner" WHERE "projectId" IS NULL`,
      `ALTER TABLE "Runner" ALTER COLUMN "projectId" SET NOT NULL`,
      `ALTER TABLE "RunbookSecret" DROP COLUMN "isAvailableToGlobalRunners"`,
      `ALTER TABLE "RunnerJob" DROP COLUMN "runsOnGlobalRunner"`,
      `ALTER TABLE "Runner" DROP COLUMN "isGlobalRunner"`,
      `ALTER TABLE "Project" DROP COLUMN "useGlobalRunners"`,
    ]);
  });
});
