import { AddHostCollectorManagement1805500000000 } from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/1805500000000-AddHostCollectorManagement";
import { AddHostCollectorManagementIndexesAndKeys1805550000000 } from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/1805550000000-AddHostCollectorManagementIndexesAndKeys";
import SchemaMigrations from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/Index";
import OnlineDdl from "../../../../Server/Infrastructure/Postgres/OnlineDdl";
import { MigrationInterface, QueryRunner } from "typeorm";
import { afterEach, describe, expect, jest, test } from "@jest/globals";

/*
 * The schema for the hosts OneUptime installs and configures. Generated by
 * TypeORM against a fully migrated database, then split in two: what is new
 * (three tables, empty) is made in one migration; what touches "Host", which
 * already holds rows in every project, is either a column that does not
 * rewrite the table, or an index and a key built online in the next one.
 * Pinned here: exactly that, nothing else, and down() undoing all of it.
 */

const NEW_TABLES: Array<string> = [
  "HostCollectorConfig",
  "HostCollectorConfigVersion",
  "HostCollectorConfigLabel",
];

const HOST_COLUMNS: Array<string> = [
  "collectorInstanceUid",
  "collectorLastContactAt",
  "collectorRegisteredAt",
  "collectorConfigId",
  "isCollectorConfigPinned",
  "collectorConfigVersionId",
  "collectorConfigHash",
  "collectorConfigStatus",
  "collectorConfigError",
  "collectorFailedConfigHash",
  "isCollectorHealthy",
  "collectorHealthError",
  "collectorHostFeatures",
];

async function run(
  migration: MigrationInterface,
  direction: "up" | "down",
): Promise<Array<string>> {
  const queries: Array<string> = [];
  const runner: QueryRunner = {
    query: async (sql: string): Promise<void> => {
      queries.push(sql);
    },
  } as unknown as QueryRunner;

  if (direction === "up") {
    await migration.up(runner);
  } else {
    await migration.down(runner);
  }

  return queries;
}

afterEach(() => {
  jest.restoreAllMocks();
});

describe("AddHostCollectorManagement1805500000000", () => {
  test("creates the three new tables, and adds the host's collector columns", async () => {
    const queries: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "up",
    );

    for (const table of NEW_TABLES) {
      expect(
        queries.filter((sql: string): boolean => {
          return sql.startsWith(`CREATE TABLE "${table}" (`);
        }).length,
      ).toBe(1);
    }

    const added: Array<string> = queries
      .filter((sql: string): boolean => {
        return sql.startsWith(`ALTER TABLE "Host" ADD "`);
      })
      .map((sql: string): string => {
        return sql.split('"')[3] as string;
      });

    expect(added).toEqual(HOST_COLUMNS);
  });

  test("no column it adds to Host rewrites the table: each is nullable, or has a constant default", async () => {
    const queries: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "up",
    );

    for (const sql of queries.filter((statement: string): boolean => {
      return statement.startsWith(`ALTER TABLE "Host" ADD "`);
    })) {
      if (sql.includes("NOT NULL")) {
        expect(sql).toMatch(/NOT NULL DEFAULT (false|true|'[^']*')$/);
      }
    }
  });

  test("touches Host only by adding columns: its indexes and keys are the next migration's", async () => {
    const queries: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "up",
    );

    const onHost: Array<string> = queries.filter((sql: string): boolean => {
      return (
        sql.includes(`"Host"`) && !sql.startsWith(`ALTER TABLE "Host" ADD "`)
      );
    });

    expect(onHost).toEqual([]);
    expect(
      queries.some((sql: string): boolean => {
        return sql.includes("DROP ");
      }),
    ).toBe(false);
  });

  test("a config's versions are numbered once per config, and go with it", async () => {
    const queries: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "up",
    );

    expect(queries).toContain(
      `CREATE UNIQUE INDEX "IDX_a6eced439492c07cf742f5ee7d" ON "HostCollectorConfigVersion" ("hostCollectorConfigId", "versionNumber") `,
    );
    expect(
      queries.some((sql: string): boolean => {
        return (
          sql.startsWith(
            `ALTER TABLE "HostCollectorConfigVersion" ADD CONSTRAINT`,
          ) &&
          sql.includes(
            `FOREIGN KEY ("hostCollectorConfigId") REFERENCES "HostCollectorConfig"("_id") ON DELETE CASCADE`,
          )
        );
      }),
    ).toBe(true);
  });

  test("configs and versions go with their project, labels with either side", async () => {
    const queries: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "up",
    );

    for (const table of ["HostCollectorConfig", "HostCollectorConfigVersion"]) {
      expect(
        queries.some((sql: string): boolean => {
          return (
            sql.startsWith(`ALTER TABLE "${table}" ADD CONSTRAINT`) &&
            sql.includes(
              `FOREIGN KEY ("projectId") REFERENCES "Project"("_id") ON DELETE CASCADE`,
            )
          );
        }),
      ).toBe(true);
    }

    for (const column of ["hostCollectorConfigId", "labelId"]) {
      expect(
        queries.some((sql: string): boolean => {
          return (
            sql.startsWith(
              `ALTER TABLE "HostCollectorConfigLabel" ADD CONSTRAINT`,
            ) &&
            sql.includes(`FOREIGN KEY ("${column}")`) &&
            sql.includes("ON DELETE CASCADE")
          );
        }),
      ).toBe(true);
    }
  });

  test("down() drops every table, column and index up() made", async () => {
    const up: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "up",
    );
    const down: Array<string> = await run(
      new AddHostCollectorManagement1805500000000(),
      "down",
    );

    for (const table of NEW_TABLES) {
      expect(down).toContain(`DROP TABLE "${table}"`);
    }

    for (const column of HOST_COLUMNS) {
      expect(down).toContain(`ALTER TABLE "Host" DROP COLUMN "${column}"`);
    }

    const createdIndexes: Array<string> = up
      .map((sql: string): string | null => {
        const match: RegExpMatchArray | null = sql.match(
          /^CREATE (?:UNIQUE )?INDEX "(IDX_[0-9a-f]+)"/,
        );
        return match ? (match[1] as string) : null;
      })
      .filter((name: string | null): name is string => {
        return name !== null;
      });

    for (const name of createdIndexes) {
      expect(down).toContain(`DROP INDEX "public"."${name}"`);
    }
  });
});

describe("AddHostCollectorManagementIndexesAndKeys1805550000000", () => {
  test("builds Host's indexes and keys online, outside a transaction", async () => {
    const indexes: Array<string> = [];
    const keys: Array<string> = [];

    jest
      .spyOn(OnlineDdl, "createIndex")
      .mockImplementation(async (_runner: QueryRunner, sql: string) => {
        indexes.push(sql);
      });
    jest
      .spyOn(OnlineDdl, "addForeignKey")
      .mockImplementation(async (_runner: QueryRunner, sql: string) => {
        keys.push(sql);
      });

    const migration: AddHostCollectorManagementIndexesAndKeys1805550000000 =
      new AddHostCollectorManagementIndexesAndKeys1805550000000();
    const queries: Array<string> = await run(migration, "up");

    expect(migration.transaction).toBe(false);
    expect(queries).toEqual([]);
    expect(
      indexes.map((sql: string): string => {
        return sql.split('"')[5] as string;
      }),
    ).toEqual([
      "collectorInstanceUid",
      "collectorConfigId",
      "collectorRegisteredAt",
    ]);
    expect(keys.length).toBe(2);
    expect(keys[0]).toContain(
      `FOREIGN KEY ("collectorConfigId") REFERENCES "HostCollectorConfig"("_id") ON DELETE SET NULL`,
    );
    expect(keys[1]).toContain(
      `FOREIGN KEY ("collectorConfigVersionId") REFERENCES "HostCollectorConfigVersion"("_id") ON DELETE SET NULL`,
    );

    // Each statement is one OnlineDdl can read.
    for (const sql of indexes) {
      expect(() => {
        OnlineDdl.parseCreateIndex(sql);
      }).not.toThrow();
    }
  });

  test("down() drops the keys, then the indexes", async () => {
    const dropped: Array<string> = [];
    jest
      .spyOn(OnlineDdl, "dropIndex")
      .mockImplementation(async (_runner: QueryRunner, sql: string) => {
        dropped.push(sql);
      });

    const queries: Array<string> = await run(
      new AddHostCollectorManagementIndexesAndKeys1805550000000(),
      "down",
    );

    expect(queries).toEqual([
      `ALTER TABLE "Host" DROP CONSTRAINT "FK_a9e31a74701da2766348096d21c"`,
      `ALTER TABLE "Host" DROP CONSTRAINT "FK_f5cbc62964363d06f038ce8c0f7"`,
    ]);
    expect(dropped.length).toBe(3);
  });
});

describe("the order the migrations run in", () => {
  test("the tables first, then Host's indexes and keys, after every migration before them", () => {
    const names: Array<string> = SchemaMigrations.map(
      (migration: unknown): string => {
        return (migration as { name: string }).name;
      },
    );

    const tables: number = names.indexOf(
      "AddHostCollectorManagement1805500000000",
    );
    const indexes: number = names.indexOf(
      "AddHostCollectorManagementIndexesAndKeys1805550000000",
    );

    expect(tables).toBeGreaterThan(-1);
    expect(indexes).toBe(tables + 1);
    expect(
      names.indexOf("AddScheduledMaintenanceExternalCalendars1805120000000"),
    ).toBeLessThan(tables);
    // After Cloud Connect's, which reached master first.
    expect(
      names.indexOf("AddCloudResourceCloudConnectionIndexAndKey1805450000000"),
    ).toBeLessThan(tables);
  });
});
