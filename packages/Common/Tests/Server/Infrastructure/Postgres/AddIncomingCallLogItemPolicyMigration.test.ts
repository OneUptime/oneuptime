import OnlineDdl from "../../../../Server/Infrastructure/Postgres/OnlineDdl";
import { AddIncomingCallLogItemPolicy1803600000000 } from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/1803600000000-AddIncomingCallLogItemPolicy";
import { AddIncomingCallLogItemPolicyIndexAndKey1803650000000 } from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/1803650000000-AddIncomingCallLogItemPolicyIndexAndKey";
import SchemaMigrations from "../../../../Server/Infrastructure/Postgres/SchemaMigrations/Index";
import { MigrationInterface, QueryRunner } from "typeorm";
import fs from "fs";
import path from "path";
import { afterEach, describe, expect, jest, test } from "@jest/globals";

/*
 * The two migrations that give each attempt of a call (IncomingCallLogItem)
 * the policy its call names, so the attempts are read with the policy, as
 * the call is. The first adds the column and gives every attempt written
 * before it its call's policy; the second indexes the column and keys it to
 * the policy online (OnlineDdl), as the table already exists. Both were
 * generated by TypeORM against a fully migrated throwaway database and
 * nothing else; what is pinned here is what they must hold. The backfill,
 * the index and the key run against Postgres in OwnedRecordsDeletePostgres
 * ("the attempts of the calls made before the change ...").
 */

const COLUMN_MIGRATION: string = "AddIncomingCallLogItemPolicy1803600000000";
const KEY_MIGRATION: string =
  "AddIncomingCallLogItemPolicyIndexAndKey1803650000000";
const TRAILING_TIMESTAMP_PATTERN: RegExp = /(\d+)$/;

const ADD_COLUMN: string = `ALTER TABLE "IncomingCallLogItem" ADD "incomingCallPolicyId" uuid`;
const BACKFILL: string = `UPDATE "IncomingCallLogItem" SET "incomingCallPolicyId" = "IncomingCallLog"."incomingCallPolicyId" FROM "IncomingCallLog" WHERE "IncomingCallLogItem"."incomingCallLogId" = "IncomingCallLog"."_id" AND "IncomingCallLogItem"."incomingCallPolicyId" IS NULL`;
const CREATE_INDEX: string = `CREATE INDEX "IDX_d728fcf2cd2e2bafbbb0ee8719" ON "IncomingCallLogItem" ("incomingCallPolicyId") `;
const ADD_KEY: string = `ALTER TABLE "IncomingCallLogItem" ADD CONSTRAINT "FK_d728fcf2cd2e2bafbbb0ee87193" FOREIGN KEY ("incomingCallPolicyId") REFERENCES "IncomingCallPolicy"("_id") ON DELETE CASCADE ON UPDATE NO ACTION`;

type MigrationClass = new () => MigrationInterface;

// What a migration runs, recorded: the statements, and the online steps.
async function record(
  migration: MigrationInterface,
  direction: "up" | "down",
): Promise<Array<string>> {
  const steps: Array<string> = [];

  const runner: QueryRunner = {
    isTransactionActive: false,
    query: async (sql: string): Promise<void> => {
      steps.push(sql);
    },
  } as unknown as QueryRunner;

  jest.spyOn(OnlineDdl, "createIndex").mockImplementation((async (
    _runner: QueryRunner,
    statement: string,
  ) => {
    steps.push(`online: ${statement}`);
  }) as never);
  jest.spyOn(OnlineDdl, "addForeignKey").mockImplementation((async (
    _runner: QueryRunner,
    statement: string,
  ) => {
    steps.push(`online: ${statement}`);
  }) as never);
  jest.spyOn(OnlineDdl, "dropIndex").mockImplementation((async (
    _runner: QueryRunner,
    statement: string,
  ) => {
    steps.push(`online: ${statement}`);
  }) as never);

  if (direction === "up") {
    await migration.up(runner);
  } else {
    await migration.down(runner);
  }

  return steps;
}

function timestampOf(migration: MigrationClass): number {
  const match: RegExpMatchArray | null = migration.name.match(
    TRAILING_TIMESTAMP_PATTERN,
  );

  return match ? parseInt(match[1]!, 10) : 0;
}

afterEach(() => {
  jest.restoreAllMocks();
});

describe("the migrations that give each attempt of a call its call's policy", () => {
  test("name themselves after their timestamps", () => {
    expect(AddIncomingCallLogItemPolicy1803600000000.name).toBe(
      COLUMN_MIGRATION,
    );
    expect(new AddIncomingCallLogItemPolicy1803600000000().name).toBe(
      COLUMN_MIGRATION,
    );
    expect(AddIncomingCallLogItemPolicyIndexAndKey1803650000000.name).toBe(
      KEY_MIGRATION,
    );
    expect(
      new AddIncomingCallLogItemPolicyIndexAndKey1803650000000().name,
    ).toBe(KEY_MIGRATION);
  });

  test("are registered once each, the key right after the column, after every migration older than them", () => {
    const registered: Array<MigrationClass> =
      SchemaMigrations as Array<MigrationClass>;

    const columnAt: number = registered.indexOf(
      AddIncomingCallLogItemPolicy1803600000000,
    );
    const keyAt: number = registered.indexOf(
      AddIncomingCallLogItemPolicyIndexAndKey1803650000000,
    );

    expect(
      registered.filter((migration: MigrationClass): boolean => {
        return (
          migration === AddIncomingCallLogItemPolicy1803600000000 ||
          migration === AddIncomingCallLogItemPolicyIndexAndKey1803650000000
        );
      }),
    ).toHaveLength(2);
    expect(columnAt).toBeGreaterThan(0);
    expect(keyAt).toBe(columnAt + 1);

    for (let before: number = 0; before < columnAt; before++) {
      expect(timestampOf(registered[before]!)).toBeLessThan(1803600000000);
    }
  });

  test("are backed by exactly one file each, carrying its timestamp", () => {
    const directory: string = path.join(
      __dirname,
      "../../../../Server/Infrastructure/Postgres/SchemaMigrations",
    );
    const files: Array<string> = fs.readdirSync(directory);

    expect(
      files.filter((file: string): boolean => {
        return file.startsWith("1803600000000-");
      }),
    ).toEqual(["1803600000000-AddIncomingCallLogItemPolicy.ts"]);
    expect(
      files.filter((file: string): boolean => {
        return file.startsWith("1803650000000-");
      }),
    ).toEqual(["1803650000000-AddIncomingCallLogItemPolicyIndexAndKey.ts"]);
  });

  test("the column is added, empty, and every attempt written before it takes its call's policy - nothing else is touched", async () => {
    expect(
      await record(new AddIncomingCallLogItemPolicy1803600000000(), "up"),
    ).toEqual([ADD_COLUMN, BACKFILL]);
  });

  test("the column migration runs in a transaction, as the column and its backfill go together", () => {
    expect(
      (
        new AddIncomingCallLogItemPolicy1803600000000() as unknown as {
          transaction?: boolean;
        }
      ).transaction,
    ).toBeUndefined();
  });

  test("the index and the key to the policy are built online, outside a transaction, exactly as generated", async () => {
    const migration: AddIncomingCallLogItemPolicyIndexAndKey1803650000000 =
      new AddIncomingCallLogItemPolicyIndexAndKey1803650000000();

    expect(migration.transaction).toBe(false);
    expect(await record(migration, "up")).toEqual([
      `online: ${CREATE_INDEX}`,
      `online: ${ADD_KEY}`,
    ]);
  });

  test("an attempt goes with its policy: the key removes it when the policy is removed", () => {
    expect(ADD_KEY).toContain(`REFERENCES "IncomingCallPolicy"("_id")`);
    expect(ADD_KEY).toContain("ON DELETE CASCADE");
  });

  test("down() undoes each of them, the key and the index before the column", async () => {
    expect(
      await record(
        new AddIncomingCallLogItemPolicyIndexAndKey1803650000000(),
        "down",
      ),
    ).toEqual([
      `ALTER TABLE "IncomingCallLogItem" DROP CONSTRAINT "FK_d728fcf2cd2e2bafbbb0ee87193"`,
      `online: DROP INDEX "public"."IDX_d728fcf2cd2e2bafbbb0ee8719"`,
    ]);
    expect(
      await record(new AddIncomingCallLogItemPolicy1803600000000(), "down"),
    ).toEqual([
      `ALTER TABLE "IncomingCallLogItem" DROP COLUMN "incomingCallPolicyId"`,
    ]);
  });
});
