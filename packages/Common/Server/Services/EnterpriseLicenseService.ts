import EnterpriseLicense from "../../Models/DatabaseModels/EnterpriseLicense";
import MarketingEventUtil from "../Utils/Marketing/MarketingEventUtil";
import { MarketingEventType } from "../../Types/Marketing/MarketingEvent";
import { OnCreate, OnDelete, OnUpdate } from "../Types/Database/Hooks";
import CreateBy from "../Types/Database/CreateBy";
import DeleteBy from "../Types/Database/DeleteBy";
import UpdateBy from "../Types/Database/UpdateBy";
import Select from "../Types/Database/Select";
import OneUptimeDate from "../../Types/Date";
import { JSONObject } from "../../Types/JSON";
import CaptureSpan from "../Utils/Telemetry/CaptureSpan";
import ObjectID from "../../Types/ObjectID";
import Semaphore, { SemaphoreMutex } from "../Infrastructure/Semaphore";
import logger from "../Utils/Logger";
import {
  buildLicenseDeletedAuditLine,
  buildLicenseIssuedAuditLine,
  buildLicenseUpdatedAuditLine,
  ENTERPRISE_LICENSE_AUDITED_COLUMNS,
  getAuditedColumnsWritten,
} from "../Utils/EnterpriseLicense/EnterpriseLicenseAudit";
import crypto from "crypto";

/*
 * Random bytes in a license key generated by the server: 256 bits, written as
 * 64 hex characters (the column holds 100). Keys issued before server-side
 * generation are browser-made UUIDs and keep working unchanged.
 */
export const ENTERPRISE_LICENSE_KEY_RANDOM_BYTES: number = 32;

export const generateEnterpriseLicenseKey: () => string = (): string => {
  return crypto
    .randomBytes(ENTERPRISE_LICENSE_KEY_RANDOM_BYTES)
    .toString("hex");
};

export const ENTERPRISE_LICENSE_USAGE_AGGREGATION_LOCK_NAMESPACE: string =
  "EnterpriseLicenseService.usageAggregation";

/*
 * What the audit hooks read of a license before a delete or an update of its
 * terms: what names it in the line (EnterpriseLicenseAudit), and the terms an
 * update can change, to say what they were.
 */
const AUDIT_SELECT: Select<EnterpriseLicense> = {
  _id: true,
  ...Object.fromEntries(
    ENTERPRISE_LICENSE_AUDITED_COLUMNS.map((column: string) => {
      return [column, true];
    }),
  ),
} as Select<EnterpriseLicense>;

// The licenses a delete or an update is about, read before it is made.
interface LicensesBeforeWrite {
  licenses: Array<EnterpriseLicense>;
}

/*
 * Writes an audit line, never failing the write it describes: the hooks
 * below run once a license is created, changed or deleted, and a TypeError
 * there would turn a write that happened into an error the admin retries
 * (see onCreateSuccess). A line that cannot be built is reported instead.
 */
export const writeEnterpriseLicenseAuditLine: (
  buildLine: () => string | null,
) => void = (buildLine: () => string | null): void => {
  try {
    const line: string | null = buildLine();

    if (line) {
      logger.info(line);
    }
  } catch (err) {
    logger.error(
      `EnterpriseLicenseService: could not write an audit line for an enterprise license change: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
};

export const ENTERPRISE_LICENSE_USAGE_AGGREGATION_LOCK_OPTIONS: Readonly<{
  namespace: string;
  lockTimeout: number;
  acquireTimeout: number;
}> = Object.freeze({
  namespace: ENTERPRISE_LICENSE_USAGE_AGGREGATION_LOCK_NAMESPACE,
  lockTimeout: 60_000,
  acquireTimeout: 10_000,
});

export class Service extends DatabaseService<EnterpriseLicense> {
  public constructor() {
    super(EnterpriseLicense);
  }

  /**
   * Serialize usage aggregation for one enterprise license across every API
   * and worker process. Callers must put the complete read-compute-write
   * operation inside `fn`; locking only the write would leave the stale-read
   * race intact.
   */
  public async runWithUsageAggregationLock<TResult>(data: {
    licenseId: ObjectID;
    fn: () => Promise<TResult>;
  }): Promise<TResult> {
    /*
     * Acquisition is deliberately outside the callback try/finally. If Redis
     * is unavailable or contention exceeds the bounded acquire timeout, the
     * operation fails closed and there is no unowned mutex to release.
     */
    const mutex: SemaphoreMutex = await Semaphore.lock({
      key: data.licenseId.toString(),
      ...ENTERPRISE_LICENSE_USAGE_AGGREGATION_LOCK_OPTIONS,
    });

    try {
      return await data.fn();
    } finally {
      try {
        await Semaphore.release(mutex);
      } catch (error) {
        /*
         * redis-semaphore refreshes held locks and lets them expire after the
         * lock timeout if explicit release fails. Logging is best effort: a
         * release error must not replace either the callback's value or its
         * more useful error.
         */
        logger.error(
          `Failed to release enterprise license usage aggregation lock for ${data.licenseId.toString()}; it will expire automatically: ${error}`,
        );
      }
    }
  }

  /*
   * A license created with no key (the Admin Dashboard's "leave blank to
   * auto-generate") gets one from the server's CSPRNG here, instead of from
   * the browser. A key typed by the admin is kept, trimmed: installations
   * trim the key they send, so stored whitespace would make it unmatchable.
   */
  @CaptureSpan()
  protected override async onBeforeCreate(
    createBy: CreateBy<EnterpriseLicense>,
  ): Promise<OnCreate<EnterpriseLicense>> {
    const providedKey: string =
      typeof createBy.data.licenseKey === "string"
        ? createBy.data.licenseKey.trim()
        : "";

    createBy.data.licenseKey = providedKey || generateEnterpriseLicenseKey();

    return {
      createBy,
      carryForward: undefined,
    };
  }

  @CaptureSpan()
  protected override async onCreateSuccess(
    onCreate: OnCreate<EnterpriseLicense>,
    createdItem: EnterpriseLicense,
  ): Promise<EnterpriseLicense> {
    // Who issued it, beside the deletes and changes (EnterpriseLicenseAudit).
    writeEnterpriseLicenseAuditLine((): string => {
      return buildLicenseIssuedAuditLine({
        license: createdItem,
        props: onCreate?.createBy?.props || {},
      });
    });

    /*
     * The outbound enterprise_license_issued conversion.
     *
     * This is where sales-led revenue enters the funnel. Everything else
     * OneUptime emits is self-serve and knows its own value from the plan
     * table; an enterprise contract is negotiated, so annualContractValue is
     * the only place the number exists at all.
     *
     * Emitted even with no email and no ACV. A licence issued without either
     * is still a licence issued, and a receiver that sees the event can chase
     * the missing detail — one that never sees it cannot. The two nulls are
     * reported honestly rather than defaulted to zero, which would quietly
     * drag reported contract value down.
     */
    MarketingEventUtil.emitInBackground(() => {
      return MarketingEventUtil.buildEvent({
        eventType: MarketingEventType.EnterpriseLicenseIssued,
        eventId: `${MarketingEventType.EnterpriseLicenseIssued}:${createdItem.id?.toString()}`,
        occurredAt: createdItem.createdAt || new Date(),
        email: createdItem.email?.toString(),
        /*
         * No attribution source. A licence row is typed in by a human and
         * carries no session, so its campaign is whatever the earlier
         * conversion sharing its email carried — the join the receiver makes
         * on emailHash, not something OneUptime can restate here.
         */
        data: {
          enterpriseLicenseId: createdItem.id?.toString() || "",
          companyName: createdItem.companyName || "",
          annualContractValueInUSD:
            createdItem.annualContractValue === undefined ||
            createdItem.annualContractValue === null
              ? null
              : createdItem.annualContractValue,
          currency: "USD",
          isEvaluationLicense: Boolean(createdItem.isEvaluationLicense),
          userLimit:
            createdItem.userLimit === undefined ||
            createdItem.userLimit === null
              ? null
              : createdItem.userLimit,
          /*
           * Read through OneUptimeDate rather than calling toISOString on the
           * column directly. TypeORM's save() returns the entity it was handed,
           * so this is whatever the caller supplied — a Date from the coercion
           * in BaseModel.fromJSON, but a raw string from any caller that skips
           * it. This hook runs AFTER the INSERT has committed, so a TypeError
           * here does not undo the licence: it only turns a licence that exists
           * into a "Server Error" the admin retries, creating another one.
           */
          expiresAt: OneUptimeDate.toIsoStringOrNull(createdItem.expiresAt),
        },
      });
    });

    return createdItem;
  }

  /*
   * The licenses a delete removes, read before it (and the delete held to
   * them), so the audit line can name each one once it is gone: its company,
   * its masked key and the expiry its installations keep running to.
   */
  @CaptureSpan()
  protected override async onBeforeDelete(
    deleteBy: DeleteBy<EnterpriseLicense>,
  ): Promise<OnDelete<EnterpriseLicense>> {
    const licenses: Array<EnterpriseLicense> =
      await this.findRowsAndHoldDeleteToThem(deleteBy, AUDIT_SELECT);

    const carryForward: LicensesBeforeWrite = { licenses };

    return { deleteBy, carryForward };
  }

  @CaptureSpan()
  protected override async onDeleteSuccess(
    onDelete: OnDelete<EnterpriseLicense>,
    itemIdsBeforeDelete: Array<ObjectID>,
  ): Promise<OnDelete<EnterpriseLicense>> {
    const carried: LicensesBeforeWrite | null =
      (onDelete.carryForward as LicensesBeforeWrite | null) || null;

    const deletedIds: Set<string> = new Set<string>(
      itemIdsBeforeDelete.map((id: ObjectID): string => {
        return id.toString();
      }),
    );

    for (const license of carried?.licenses || []) {
      if (!license.id || !deletedIds.has(license.id.toString())) {
        continue;
      }

      writeEnterpriseLicenseAuditLine((): string => {
        return buildLicenseDeletedAuditLine({
          license,
          props: onDelete.deleteBy.props,
        });
      });
    }

    return onDelete;
  }

  /*
   * An update that writes a license's terms - the edit form, the list's bulk
   * expiry change, the API - reads the licenses it changes first (and is held
   * to them), so the audit line can say what each term was. An update of
   * anything else is left alone.
   */
  @CaptureSpan()
  protected override async onBeforeUpdate(
    updateBy: UpdateBy<EnterpriseLicense>,
  ): Promise<OnUpdate<EnterpriseLicense>> {
    if (
      getAuditedColumnsWritten(updateBy.data as unknown as JSONObject)
        .length === 0
    ) {
      return { updateBy, carryForward: null };
    }

    const licenses: Array<EnterpriseLicense> =
      await this.findRowsAndHoldUpdateToThem(updateBy, AUDIT_SELECT);

    const carryForward: LicensesBeforeWrite = { licenses };

    return { updateBy, carryForward };
  }

  @CaptureSpan()
  protected override async onUpdateSuccess(
    onUpdate: OnUpdate<EnterpriseLicense>,
    updatedItemIds: Array<ObjectID>,
  ): Promise<OnUpdate<EnterpriseLicense>> {
    const carried: LicensesBeforeWrite | null =
      (onUpdate.carryForward as LicensesBeforeWrite | null) || null;

    if (!carried) {
      return onUpdate;
    }

    const updatedIds: Set<string> = new Set<string>(
      updatedItemIds.map((id: ObjectID): string => {
        return id.toString();
      }),
    );

    for (const license of carried.licenses) {
      if (!license.id || !updatedIds.has(license.id.toString())) {
        continue;
      }

      writeEnterpriseLicenseAuditLine((): string | null => {
        return buildLicenseUpdatedAuditLine({
          before: license,
          written: onUpdate.updateBy.data as unknown as JSONObject,
          props: onUpdate.updateBy.props,
        });
      });
    }

    return onUpdate;
  }
}

export default new Service();
