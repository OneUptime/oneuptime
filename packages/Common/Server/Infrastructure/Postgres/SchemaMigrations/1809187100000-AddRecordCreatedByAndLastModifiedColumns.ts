/*
 * WHAT CREATED EACH RECORD AND WHAT LAST MODIFIED IT, ON EVERY TABLE (#10290).
 *
 * Every model now keeps, on the base model (Types/Database/RecordActor),
 * what created a record - a person, an API key, a workflow, an MCP client, a
 * server admin or OneUptime itself, and which key, workflow or client - and
 * when a person, a key, a workflow or an MCP client last modified it, and who.
 * Six nullable columns on each of the 629 tables, exactly as
 * `npm run generate-postgres-migration` wrote them, and nothing else: no
 * default, no index, no foreign key (the base model says why).
 *
 * A nullable column with no default is a change of the table's catalog
 * entry: Postgres rewrites no row and scans none. But ALTER TABLE takes
 * ACCESS EXCLUSIVE on its table, and a migration holds every lock it takes
 * until it commits (SchemaMigrationRunner). In one transaction this would
 * hold every table in the database - "Monitor", "Project", "User" and every
 * other - until the last of them was altered. So it runs outside one
 * (transaction = false), one statement per table with all six columns, and
 * each table is held for the instant its own statement takes.
 *
 * Not in a transaction, a stop part way leaves the tables before it altered,
 * and the runner starts it again from the top: a table that already has all
 * six columns is passed by without asking for its lock again, and the rest
 * add only what they lack (ADD COLUMN IF NOT EXISTS). The drift check
 * (npm run check-postgres-schema-drift) reads the result, not these
 * statements, so the schema it reads is the generator's.
 */

