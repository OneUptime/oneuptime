// One table's six columns, in one statement: one lock, for an instant.
export const getAddRecordActorColumnsStatement: (table: string) => string = (
  table: string,
): string => {
  return `ALTER TABLE "${table}" ${RECORD_ACTOR_COLUMN_DEFINITIONS.map(
    (column: { name: string; definition: string }): string => {
      return `ADD COLUMN IF NOT EXISTS "${column.name}" ${column.definition}`;
    },
  ).join(", ")}`;
};

// And back: the columns in the order the generator drops them.
export const getDropRecordActorColumnsStatement: (table: string) => string = (
  table: string,
): string => {
  return `ALTER TABLE "${table}" ${[...RECORD_ACTOR_COLUMN_DEFINITIONS]
    .reverse()
    .map((column: { name: string; definition: string }): string => {
      return `DROP COLUMN IF EXISTS "${column.name}"`;
    })
    .join(", ")}`;
};

