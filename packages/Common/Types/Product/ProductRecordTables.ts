/*
 * EVERY RECORD OF A PRODUCT, FOR THE REFUSAL OF ITS WRITES (#7479).
 *
 * While a product is switched off on the server (Types/Product/
 * ServerProducts), nobody may create, change or delete its records: not
 * through the API, a custom route, a workflow's step, the Slack, Microsoft
 * Teams or Mattermost app, Ask AI or an MCP client. PRODUCT_OF_TABLE holds a
 * product's main record (a monitor, a status page); this holds every table
 * of it - the main record and the records that hang off it: a status page's
 * announcements, subscribers and domains, a workflow's variables, an on-call
 * policy's schedules and escalation rules, a monitor's groups.
 *
 * A table serves one product, or a few that share it (a data store is Data
 * Observability's and Data Security's): its writes are refused only while
 * every product it serves is off, so a product that stays on keeps working.
 * A table that is every product's - a person, a project, a team, a label,
 * a notification method - is in TABLES_OF_NO_PRODUCT, with why. Every table
 * of the server is in one or the other (ProductRecordTables.test.ts holds
 * it to every model), so a new table is a decision, never forgotten.
 *
 * Reads are never refused: products that stay on show records of others.
 * Nor is the server's own work, done as root: monitors keep checking,
 * published status pages keep their subscribers, and telemetry keeps
 * arriving (ServerProducts).
 *
 * By table name, as the models and the analytics models name their tables.
 * Pure: the server and its tests read it.
 */
