// Table -> the products it serves, built once.
const PRODUCTS_OF_TABLE: ReadonlyMap<
  string,
  ReadonlyArray<ProductKey>
> = ((): Map<string, Array<ProductKey>> => {
  const map: Map<string, Array<ProductKey>> = new Map();

  for (const product of Object.keys(PRODUCT_RECORD_TABLES) as Array<
    keyof typeof PRODUCT_RECORD_TABLES
  >) {
    for (const table of PRODUCT_RECORD_TABLES[product] || []) {
      const products: Array<ProductKey> = map.get(table) || [];

      if (!products.includes(product)) {
        products.push(product);
      }

      map.set(table, products);
    }
  }

  return map;
})();

/*
 * The products whose records a table holds - one, or the few that share it
 * - or none for a table of no product, or one this file does not know.
 */
export const getProductsOfRecordTable: (
  tableName: string | null | undefined,
) => ReadonlyArray<ProductKey> = (
  tableName: string | null | undefined,
): ReadonlyArray<ProductKey> => {
  if (!tableName) {
    return [];
  }

  return PRODUCTS_OF_TABLE.get(tableName) || [];
};

/*
 * The product a write to this table is refused for, given what is off: the
 * first product it serves, once every product it serves is off. Null while
 * one of them is on, and for a table of no product.
 */
export const getOffProductOfRecordTable: (data: {
  tableName: string | null | undefined;
  isOff: (product: ProductKey) => boolean;
}) => ProductKey | null = (data: {
  tableName: string | null | undefined;
  isOff: (product: ProductKey) => boolean;
}): ProductKey | null => {
  const products: ReadonlyArray<ProductKey> = getProductsOfRecordTable(
    data.tableName,
  );

  if (products.length === 0) {
    return null;
  }

  return products.every(data.isOff) ? products[0]! : null;
};
