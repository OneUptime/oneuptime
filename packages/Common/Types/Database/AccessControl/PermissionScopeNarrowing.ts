/*
 * WHAT A SCOPE NARROWS, PERMISSION BY PERMISSION.
 *
 * Every permission a team, a custom role or an API key is given can be
 * limited: to the records that carry some labels, or - on a team or a
 * custom role - to the records the person, or the team given it, owns
 * (PermissionScope). The server honours the limit on every row, whatever
 * the permission (Server/Types/Database/Permissions). What it narrows
 * depends on the records the permission reaches:
 *
 *   - labels narrow a permission on records that carry labels (a monitor,
 *     a workflow), or that belong to or name records that do (an incident's
 *     notes, through their incident; an on-call policy's user overrides,
 *     through their policy), and on telemetry kept per resource;
 *   - owners narrow a permission on records that have owners, or take them
 *     from a parent (@OwnedThrough), for the operations the Owned scope
 *     holds to them (OwnedScopePermission.narrowsRecords).
 *
 * A permission on anything else - a team, a label, an incident state - is
 * the same for everyone who holds it. A scope narrows nothing of it, and a
 * row given one reaches the whole project whatever it says. Nor does a
 * scope narrow a role that reaches the whole project by definition
 * (PermissionHelper.isScopeApplicable: Project Owner, Project Admin, the
 * Settings and Billing roles), so none of those is listed here.
 *
 * The dashboard's Add Permission dialogs offer a scope where it narrows,
 * and only the answers that do (Dashboard/Components/Permission/
 * PermissionScopeChoice). The flag they read before
 * (PermissionProps.isAccessControlPermission) marks little more than a
 * resource's own read, edit and delete, so Create Workflow or Create
 * On-Call Duty Policy User Override could not be scoped there, though the
 * server scopes both (issue #5602) - and a few permissions it marked, a
 * network site type's among them, were offered labels that narrow nothing.
 *
 * Worked out from the models by the server's own rules, and written down
 * here because the dashboard carries no server code.
 * PermissionScopeNarrowingGuard.test.ts (Tests/Server/Types/Database/
 * Permissions) works it out again from every model and fails, naming each
 * permission to add, move or remove, whenever a model or a permission
 * changes what a scope narrows. Each list is in alphabetical order.
 */

export enum NarrowedBy {
  Labels = "Labels",
  Owners = "Owners",
  LabelsAndOwners = "LabelsAndOwners",
}

