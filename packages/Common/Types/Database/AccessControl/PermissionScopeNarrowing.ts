// The lists above, by permission: what narrows each one.
let narrowedByPermission: Map<Permission, NarrowedBy> | null = null;

const getNarrowedByPermission: () => Map<Permission, NarrowedBy> = (): Map<
  Permission,
  NarrowedBy
> => {
  if (!narrowedByPermission) {
    narrowedByPermission = new Map<Permission, NarrowedBy>();

    for (const permission of NARROWED_BY_LABELS_AND_OWNERS) {
      narrowedByPermission.set(permission, NarrowedBy.LabelsAndOwners);
    }

    for (const permission of NARROWED_BY_LABELS) {
      narrowedByPermission.set(permission, NarrowedBy.Labels);
    }

    for (const permission of NARROWED_BY_OWNERS) {
      narrowedByPermission.set(permission, NarrowedBy.Owners);
    }
  }

  return narrowedByPermission;
};

export default class PermissionScopeNarrowing {
  // Each list as written, for the guard test that holds them to the models.
  public static readonly NARROWED_BY_LABELS_AND_OWNERS: ReadonlyArray<Permission> =
    NARROWED_BY_LABELS_AND_OWNERS;

  public static readonly NARROWED_BY_LABELS: ReadonlyArray<Permission> =
    NARROWED_BY_LABELS;

  public static readonly NARROWED_BY_OWNERS: ReadonlyArray<Permission> =
    NARROWED_BY_OWNERS;

  // What narrows `permission`: labels, owners or both - null for neither.
  public static getNarrowedBy(permission: Permission): NarrowedBy | null {
    return getNarrowedByPermission().get(permission) || null;
  }

  public static isNarrowedByLabels(permission: Permission): boolean {
    const narrowedBy: NarrowedBy | null =
      PermissionScopeNarrowing.getNarrowedBy(permission);

    return (
      narrowedBy === NarrowedBy.Labels ||
      narrowedBy === NarrowedBy.LabelsAndOwners
    );
  }

  public static isNarrowedByOwners(permission: Permission): boolean {
    const narrowedBy: NarrowedBy | null =
      PermissionScopeNarrowing.getNarrowedBy(permission);

    return (
      narrowedBy === NarrowedBy.Owners ||
      narrowedBy === NarrowedBy.LabelsAndOwners
    );
  }

  public static isNarrowedByAnyScope(permission: Permission): boolean {
    return PermissionScopeNarrowing.getNarrowedBy(permission) !== null;
  }

  /*
   * The scopes that mean what they say for `permission`, in the order a
   * form offers them: All first, then Owned where owners narrow it, then
   * Labels where labels do. All alone for one no scope narrows.
   */
  public static getScopes(permission: Permission): Array<PermissionScope> {
    const scopes: Array<PermissionScope> = [PermissionScope.All];

    if (PermissionScopeNarrowing.isNarrowedByOwners(permission)) {
      scopes.push(PermissionScope.Owned);
    }

    if (PermissionScopeNarrowing.isNarrowedByLabels(permission)) {
      scopes.push(PermissionScope.Labels);
    }

    return scopes;
  }
}
