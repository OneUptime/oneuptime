/*
 * What happened to a cloud account that people should be able to look up:
 * how it came to OneUptime (CloudAccountCreated: the cloud connection that
 * first read it, or who added it), its Cloud AI agent connecting, being
 * reset or changing what OneUptime AI may do there through its own
 * configuration, and every change a person made to that (investigation,
 * fixes, the command allowlist, log reads), with who made it and what it
 * was before (CloudAccountUpdated). Every other resource an AI
 * agent serves keeps the same entries on its own feed (DockerHostFeed,
 * HostFeed, ...); an account had none, so what its agent did to its own
 * standing - the agent that holds the only credentials that can change the
 * account - went unrecorded.
 *
 * Append-only: nothing may update or delete an entry, and only OneUptime
 * writes them (as root, CloudAccountFeedService). Read with the account:
 * a feed entry is visible to whoever may read its account, and to nobody
 * else (CanAccessIfCanReadOn). The account's permissions are the Cloud
 * Resource ones, so its feed's are the Cloud Resource feed's.
 */
export enum CloudAccountFeedEventType {
  CloudAccountCreated = "CloudAccountCreated",
  CloudAccountUpdated = "CloudAccountUpdated",
}

