import { StringUtils } from "../../TerraformProvider/Core/StringUtils";
import {
  TerraformAttribute,
  TerraformResource,
  TerraformServerOwned,
} from "../../TerraformProvider/Core/Types";
import { TERRAFORM_PREFIX } from "./References";

/*
 * Resource -> field -> how OneUptime owns it, all by their Terraform names:
 * { oneuptime_monitor: { current_monitor_status_id: "after-create",
 * telemetry_monitor_last_monitor_at: "always", labels: "shared" } }.
 */
export type ServerOwnedMap = Record<
  string,
  Record<string, TerraformServerOwned>
>;

/*
 * Resource -> the fields people and OneUptime both change that no create
 * sends, by their Terraform names: only an update writes them.
 */
export type SharedUpdateOnlyMap = Record<string, Array<string>>;

/*
 * The fields OneUptime keeps once a record exists, or changes too, from the
 * spec's x-oneuptime-server-owned (TableColumnMetadata.serverOwned in the
 * models), as the Terraform provider's parser read them (#9985, #10052):
 *
 *   - "always": a read-only attribute, so a field of status.atProvider
 *     alone; config/provider.go holds the generated kinds to that;
 *   - "after-create": a field a manifest may give to create the record,
 *     which late initialization never copies into spec.forProvider
 *     (config/provider.go), and the Terraform provider never compares after
 *     the create;
 *   - "shared": a field people set and OneUptime changes too, which late
 *     initialization never copies either, and whose manifest value is sent
 *     when it changes (config/lastapplied.go).
 */
export function collectServerOwned(
  resources: Array<TerraformResource>,
): ServerOwnedMap {
  const serverOwned: ServerOwnedMap = {};

  for (const resource of resources) {
    for (const [field, attribute] of Object.entries(resource.schema)) {
      if (!attribute.serverOwned || field === "id") {
        continue;
      }
      const terraformName: string = `${TERRAFORM_PREFIX}_${resource.name}`;
      serverOwned[terraformName] = serverOwned[terraformName] || {};
      // As the provider names it: a cluster's provider is provider_value.
      serverOwned[terraformName]![StringUtils.toTerraformAttributeName(field)] =
        attribute.serverOwned;
    }
  }

  return serverOwned;
}

/*
 * The shared fields no create sends - a cluster's AI settings, which only an
 * update writes: what is recorded as applied before the create leaves them
 * out, so the reconcile after it sends the manifest's value
 * (config/lastapplied.go).
 */
export function collectSharedUpdateOnly(
  resources: Array<TerraformResource>,
): SharedUpdateOnlyMap {
  const updateOnly: SharedUpdateOnlyMap = {};

  for (const resource of resources) {
    const create: Record<string, TerraformAttribute> =
      resource.operationSchemas?.create || {};

    for (const [field, attribute] of Object.entries(resource.schema)) {
      if (attribute.serverOwned !== "shared" || field === "id") {
        continue;
      }
      if (Object.prototype.hasOwnProperty.call(create, field)) {
        continue;
      }
      const terraformName: string = `${TERRAFORM_PREFIX}_${resource.name}`;
      updateOnly[terraformName] = updateOnly[terraformName] || [];
      updateOnly[terraformName]!.push(
        StringUtils.toTerraformAttributeName(field),
      );
    }
  }

  for (const fields of Object.values(updateOnly)) {
    fields.sort();
  }

  return updateOnly;
}

function goString(value: string): string {
  return JSON.stringify(value);
}

/*
 * config/zz_server_owned.go: the fields as Go maps, in a stable order so the
 * file only changes when a model's declaration does.
 */
export function renderServerOwnedGo(
  serverOwned: ServerOwnedMap,
  sharedUpdateOnly: SharedUpdateOnlyMap = {},
): string {
  const lines: Array<string> = [
    "// Code generated by Scripts/CrossplaneProvider from the OpenAPI spec's x-oneuptime-server-owned. DO NOT EDIT.",
    "",
    "package config",
    "",
    "// generatedServerOwned names, for each resource, the fields OneUptime keeps",
    '// once its record exists: "always" when only OneUptime writes them,',
    '// "after-create" when a manifest may give the value the record starts with,',
    '// and "shared" when people set them and OneUptime changes them too.',
    "var generatedServerOwned = map[string]map[string]string{",
  ];

  for (const terraformName of Object.keys(serverOwned).sort()) {
    const fields: Record<string, string> = serverOwned[terraformName]!;
    lines.push(`\t${goString(terraformName)}: {`);
    for (const field of Object.keys(fields).sort()) {
      lines.push(`\t\t${goString(field)}: ${goString(fields[field]!)},`);
    }
    lines.push("\t},");
  }

  lines.push(
    "}",
    "",
    "// generatedSharedUpdateOnly names, for each resource, the fields people and",
    "// OneUptime both change that no create sends: only an update writes them.",
    "var generatedSharedUpdateOnly = map[string][]string{",
  );

  for (const terraformName of Object.keys(sharedUpdateOnly).sort()) {
    const fields: Array<string> = sharedUpdateOnly[terraformName]!;
    lines.push(
      `\t${goString(terraformName)}: {${fields.map(goString).join(", ")}},`,
    );
  }

  lines.push("}", "");
  return lines.join("\n");
}
