import {
  TerraformAttribute,
  TerraformResource,
} from "../../TerraformProvider/Core/Types";

/*
 * Resource -> field -> the resource the field holds the ID of, all by their
 * Terraform names: { oneuptime_monitor: { labels: "oneuptime_label" } }.
 */
export type ReferenceMap = Record<string, Record<string, string>>;

export const TERRAFORM_PREFIX: string = "oneuptime";

/*
 * Whether a field can be set: a reference fills in a field the manifest
 * would otherwise give, so a field OneUptime alone writes takes none.
 */
function isSettable(attribute: TerraformAttribute): boolean {
  return Boolean(
    attribute.required || attribute.optional || !attribute.computed,
  );
}

/*
 * The references of every resource, from the spec's relations (each
 * x-oneuptime-relation the OpenAPI parser resolved): a field that holds the
 * ID of another resource - or a list of them - takes a reference to its
 * managed resource as well, which Crossplane resolves to the ID. A relation
 * to a record OneUptime has no resource for (a user, a scan) has no managed
 * resource to refer to, so it takes the ID only.
 */
export function collectReferences(
  resources: Array<TerraformResource>,
): ReferenceMap {
  const names: Set<string> = new Set<string>(
    resources.map((resource: TerraformResource): string => {
      return resource.name;
    }),
  );
  const references: ReferenceMap = {};

  for (const resource of resources) {
    for (const [field, attribute] of Object.entries(resource.schema)) {
      const target: string | undefined = attribute.relation?.name;
      if (
        !target ||
        attribute.relation?.dataSourceOnly ||
        !names.has(target) ||
        !isSettable(attribute)
      ) {
        continue;
      }
      const terraformName: string = `${TERRAFORM_PREFIX}_${resource.name}`;
      references[terraformName] = references[terraformName] || {};
      references[terraformName]![field] = `${TERRAFORM_PREFIX}_${target}`;
    }
  }

  return references;
}

function goString(value: string): string {
  return JSON.stringify(value);
}

/*
 * config/zz_references.go: the references as a Go map, in a stable order so
 * the file only changes when a relation does.
 */
export function renderReferencesGo(references: ReferenceMap): string {
  const lines: Array<string> = [
    "// Code generated by Scripts/CrossplaneProvider from the OpenAPI spec's relations. DO NOT EDIT.",
    "",
    "package config",
    "",
    "// generatedReferences names, for each resource, the fields that hold the",
    "// IDs of another resource, and that resource.",
    "var generatedReferences = map[string]map[string]string{",
  ];

  for (const terraformName of Object.keys(references).sort()) {
    const fields: Record<string, string> = references[terraformName]!;
    lines.push(`\t${goString(terraformName)}: {`);
    for (const field of Object.keys(fields).sort()) {
      lines.push(`\t\t${goString(field)}: ${goString(fields[field]!)},`);
    }
    lines.push("\t},");
  }

  lines.push("}", "");
  return lines.join("\n");
}
